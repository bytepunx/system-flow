package designsystem

import (
	"strings"
	"testing"
)

const starterPath = "design/system/design-system.tokens.json"

// starter is the starter token file, read as flai design init writes it.
func starter(t *testing.T) *System {
	t.Helper()
	sys := load(t, StarterTokens)
	if len(sys.Problems) != 0 {
		t.Fatalf("the starter token file has problems: %+v", sys.Problems)
	}
	return sys
}

func TestStylesheetGolden(t *testing.T) {
	golden(t, "starter.stylesheet.css.golden", []byte(Stylesheet(starter(t), starterPath)))
}

func TestStylesheetIsTheHeaderThenTailwind(t *testing.T) {
	sys := starter(t)
	got := Stylesheet(sys, starterPath)
	header, rest, ok := strings.Cut(got, "*/\n\n")
	if !ok || rest != Tailwind(sys) {
		t.Fatalf("Stylesheet is not a comment header then Tailwind's rendering:\n%s", got)
	}
	for _, want := range []string{"/* Generated by flai design css --write from " + starterPath, "Do not edit"} {
		if !strings.Contains(header, want) {
			t.Errorf("the header has no %q:\n%s", want, header)
		}
	}
	if !strings.HasPrefix(rest, darkVariant+"\n@theme {\n") {
		t.Errorf("Tailwind's rendering does not open with the dark variant, then @theme:\n%s", rest)
	}
}

func TestStylesheetOfAFileThatDoesNotParse(t *testing.T) {
	if got := Stylesheet(load(t, []byte(`{"color": `)), starterPath); got != "" {
		t.Errorf("Stylesheet = %q, want empty", got)
	}
}

func TestStale(t *testing.T) {
	sys := starter(t)
	fresh := Stylesheet(sys, starterPath)
	_, noHeader, _ := strings.Cut(fresh, "*/\n\n")
	cases := []struct {
		name    string
		content string
		want    bool
	}{
		{"identical", fresh, false},
		{"CRLF line endings", strings.ReplaceAll(fresh, "\n", "\r\n"), false},
		{"a changed value", strings.Replace(fresh, "--spacing: ", "--spacing: 2*", 1), true},
		{"no header", noHeader, true},
		{"another token file named", Stylesheet(sys, "tokens.json"), true},
		{"a trailing blank line", fresh + "\n", true},
		{"empty", "", true},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := Stale(sys, starterPath, []byte(c.content)); got != c.want {
				t.Errorf("Stale = %v, want %v", got, c.want)
			}
		})
	}
}
